#!/usr/bin/env python3
"""Validate real store exports and optionally stage a self-contained upload manifest.

Sources checked 2026-10-28: Apple screenshot specifications and Google Play
Help 9866151. This verifies files, not truthfulness, translation or store acceptance.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import sys
from PIL import Image

EXTENSIONS = {'.png', '.jpg', '.jpeg'}
IOS_SIZES = {
    'APP_IPHONE_61': {(1179, 2556), (1206, 2622)},
    'APP_IPHONE_67': {(1260, 2736), (1290, 2796), (1320, 2868)},
    'APP_IPHONE_65': {(1242, 2688), (1284, 2778)},
    'APP_IPHONE_DUO': {(1398, 2034), (2007, 2853)},
    'APP_IPAD_PRO_3GEN_129': {(2048, 2732), (2064, 2752)},
}
ANDROID_TYPES = {'phone': 'phoneScreenshots', 'seven-inch': 'sevenInchScreenshots',
                 'ten-inch': 'tenInchScreenshots', 'tv': 'tvScreenshots',
                 'wear': 'wearScreenshots'}
LARGE = {'seven-inch', 'ten-inch'}

def digest(path, algorithm):
    return hashlib.new(algorithm, path.read_bytes()).hexdigest()

def image_info(path, platform, device=None):
    if path.is_symlink() or path.suffix.lower() not in EXTENSIONS:
        raise ValueError(f'Unsupported image or symlink: {path.name}')
    with Image.open(path) as im:
        im.load()
        if im.format not in {'PNG', 'JPEG'} or (im.format == 'PNG') != (path.suffix.lower() == '.png'):
            raise ValueError(f'Image content/extension mismatch: {path.name}')
        if im.mode != 'RGB' or 'transparency' in im.info:
            raise ValueError(f'Use flattened RGB PNG/JPEG without alpha: {path.name}')
        w, h = im.size
    small, large = sorted((w, h))
    kind = None
    if platform == 'ios':
        kind = next((key for key, sizes in IOS_SIZES.items() if (small, large) in sizes), None)
        if not kind:
            raise ValueError(f'Unsupported Apple screenshot size {w}x{h}: {path.name}')
    elif device in LARGE:
        if small < 1080 or large > 7680 or abs(large / small - 16 / 9) > .002:
            raise ValueError(f'Large screen needs 1080..7680px and 16:9/9:16: {path.name}')
    elif device == 'wear':
        if w != h or w < 384 or w > 3840:
            raise ValueError(f'Wear screenshot must be square, 384..3840px: {path.name}')
    else:
        if small < 320 or large > 3840 or large > 2 * small:
            raise ValueError(f'Play screenshot needs 320..3840px, ratio <=2: {path.name}')
        if device == 'tv' and w <= h:
            raise ValueError(f'TV screenshot must be landscape: {path.name}')
    return {'width': w, 'height': h, 'format': 'PNG' if path.suffix.lower() == '.png' else 'JPEG',
            'alpha': False, 'display_type': kind,
            **{key: digest(path, key) for key in ['md5', 'sha1', 'sha256']}}

def filename_order(path):
    # card number first, then Duo outer -> inner; filenames are generated by renderer.
    name = path.name
    card = int(re.match(r'\d+', name)[0]) if re.match(r'\d+', name) else 9999
    posture = 0 if 'duoOuter' in name else 1 if 'duoInner' in name else 0
    return card, posture, name

def build_manifest(root, platform, locales=None, devices=None, require=None, provenance=False):
    root = Path(root).resolve()
    if not root.is_dir():
        raise ValueError(f'Screenshot directory missing: {root}')
    locales = locales or sorted(p.name for p in root.iterdir() if p.is_dir() and not p.name.startswith('.'))
    if not locales:
        raise ValueError('No screenshot locales found')
    if provenance:
        status = json.loads((root / 'export-status.json').read_text())
        if status.get('production_ready') is not True or not set(locales) <= set(status.get('locales', [])):
            raise ValueError('Missing real captures or ready translations; run production export')
    require = require or {}
    sets = []
    for locale in locales:
        if not re.fullmatch(r'[a-zA-Z]{2,3}(?:-[a-zA-Z0-9]+)*', locale):
            raise ValueError(f'Invalid locale: {locale}')
        directory = root / locale
        if not directory.is_dir() or directory.is_symlink():
            raise ValueError(f'Missing locale: {locale}')
        groups = {}
        if platform == 'ios':
            files = sorted((p for p in directory.iterdir() if p.suffix.lower() in EXTENSIONS), key=filename_order)
            if any(p.is_dir() for p in directory.iterdir()):
                raise ValueError(f'Keep captures/work files outside the flat upload locale: {locale}')
            for path in files:
                info = image_info(path, platform)
                groups.setdefault(info['display_type'], []).append((path, info))
            expected = devices or ['APP_IPHONE_61']
            for kind in expected:
                if not groups.get(kind):
                    raise ValueError(f'Missing required display {locale}/{kind}')
            if 'APP_IPHONE_DUO' in expected:
                postures = {tuple(sorted((x[1]['width'], x[1]['height']))) for x in groups['APP_IPHONE_DUO']}
                if postures != IOS_SIZES['APP_IPHONE_DUO']:
                    raise ValueError(f'Duo needs real outer and inner exports: {locale}')
        else:
            selected = devices or list(require) or sorted(p.name for p in directory.iterdir() if p.is_dir())
            if not selected:
                raise ValueError(f'Empty screenshot locale: {locale}')
            for device in selected:
                if device not in ANDROID_TYPES:
                    raise ValueError(f'Unsupported Play category: {device}; configure a dedicated form-factor workflow')
                folder = directory / device
                if not folder.is_dir() or folder.is_symlink():
                    raise ValueError(f'Missing device folder: {locale}/{device}')
                files = sorted(p for p in folder.iterdir() if p.suffix.lower() in EXTENSIONS)
                minimum = require.get(device, 4 if device in LARGE else 1)
                if len(files) < minimum:
                    raise ValueError(f'{locale}/{device}: need {minimum} screenshots, found {len(files)}')
                groups[ANDROID_TYPES[device]] = [(p, image_info(p, platform, device)) for p in files]
            if sum(map(len, groups.values())) < 2:
                raise ValueError(f'{locale}: Play listing needs at least two screenshots in total')
        if not groups:
            raise ValueError(f'No screenshots: {locale}')
        for kind, entries in groups.items():
            maximum = 10 if platform == 'ios' else 8
            if not 1 <= len(entries) <= maximum:
                raise ValueError(f'{locale}/{kind}: {len(entries)} images, maximum {maximum} (Duo postures share one set)')
            hashes = [info['sha256'] for _, info in entries]
            if len(hashes) != len(set(hashes)):
                raise ValueError(f'Duplicate screenshots: {locale}/{kind}')
            sets.append({'locale': locale, 'display_type': kind, 'images': [
                {**info, 'path': p.relative_to(root).as_posix(), 'position': i + 1}
                for i, (p, info) in enumerate(entries)]})
    return {'schema_version': 1, 'platform': platform, 'root': str(root), 'sets': sets}

def stage(manifest, dest):
    dest = Path(dest).resolve()
    source = Path(manifest['root'])
    if dest == source or source in dest.parents or dest in source.parents:
        raise ValueError('Upload staging must be separate from source')
    # Only replace owned image sets, preserving other metadata and device sets.
    for entry in manifest['sets']:
        folder = dest / entry['locale']
        if manifest['platform'] == 'android':
            folder /= 'images/' + entry['display_type']
        folder.mkdir(parents=True, exist_ok=True)
        if folder.is_symlink():
            raise ValueError('Symlink upload folder is not allowed')
        if manifest['platform'] == 'ios':
            for p in folder.iterdir():
                if p.suffix.lower() in EXTENSIONS and image_info(p, 'ios')['display_type'] == entry['display_type']:
                    p.unlink()
        else:
            for p in folder.iterdir():
                if p.suffix.lower() in EXTENSIONS:
                    p.unlink()
        for image in entry['images']:
            original = source / image['path']
            target = folder / f"{image['position']:02d}_{entry['display_type']}_{original.name}"
            shutil.copy2(original, target)
            image['path'] = target.relative_to(dest).as_posix()
    manifest['root'] = str(dest)
    return manifest

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--platform', choices=['ios', 'android'], required=True)
    parser.add_argument('--root', type=Path, required=True)
    parser.add_argument('--locales', help='Comma-separated explicit expected locales')
    parser.add_argument('--devices', help='Comma-separated display types or Play categories')
    parser.add_argument('--require', action='append', default=[], help='Play category=count')
    parser.add_argument('--stage', type=Path)
    parser.add_argument('--manifest', type=Path)
    parser.add_argument('--require-provenance', action='store_true')
    args = parser.parse_args()
    try:
        require = {}
        for value in args.require:
            key, count = value.split('='); require[key] = int(count)
            if require[key] < 1:
                raise ValueError('Minimum count must be positive')
        split = lambda value: value.split(',') if value else None
        result = build_manifest(args.root, args.platform, split(args.locales), split(args.devices), require, args.require_provenance)
        if args.stage:
            result = stage(result, args.stage)
        if args.manifest:
            args.manifest.parent.mkdir(parents=True, exist_ok=True)
            args.manifest.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n')
        print(f"Validated {len(result['sets'])} {args.platform} screenshot sets")
        return 0
    except (ValueError, OSError, Image.UnidentifiedImageError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        return 1

if __name__ == '__main__':
    sys.exit(main())
